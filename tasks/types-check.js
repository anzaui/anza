#!/usr/bin/env node
/**
 * tasks/types-check.js
 *
 * Fails when a runtime export of @anzaui/anza has no type declaration.
 *
 * For every JS subpath in library/package.json "exports":
 *   - the subpath must have a "types" condition, and
 *   - every name the runtime module exports (static analysis, following
 *     `export *`) must also be exported by its .d.ts.
 *
 * Names a .d.ts declares but the runtime does not export are reported as
 * warnings (they type-check but fail at runtime); pass --strict to fail on them.
 *
 * The root types file (types/index.d.ts) is generated from src/index.js and
 * the module types; it must be up to date (--write-root regenerates it).
 *
 * Usage: node tasks/types-check.js [--strict] [--write-root]   (npm run types:check)
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { join, relative } from 'node:path';
import { LIB, subpaths, exportReader } from './lib/exports.js';

const strict = process.argv.includes('--strict');
const sp = subpaths();
const read = exportReader([...sp.values()].flatMap((v) => [v.runtime, v.types]));

const errors = [];
const warnings = [];
let checked = 0;

for (const [key, { pattern, runtime, types }] of sp) {
  if (pattern || !runtime || !/\.m?js$/.test(runtime)) continue;
  const rt = read(runtime);
  if (!rt) {
    errors.push(`${key}: cannot read ${relative(LIB, runtime)}`);
    continue;
  }
  checked++;
  if (!types) {
    errors.push(`${key}: no "types" condition in package.json exports`);
    continue;
  }
  const ty = read(types);
  if (!ty) {
    errors.push(`${key}: types file ${relative(LIB, types)} not found`);
    continue;
  }
  for (const name of rt.names) {
    if (!ty.names.has(name)) errors.push(`${key}: '${name}' is exported at runtime but has no type`);
  }
  for (const name of ty.names) {
    if (!rt.names.has(name) && !isTypeOnly(ty, name)) {
      const why = rt.ambiguous.has(name) ? 'ambiguous at runtime (two export * provide it)' : 'not exported at runtime';
      warnings.push(`${key}: '${name}' is typed but ${why}`);
    }
  }
}

/** Interfaces and type aliases have no runtime counterpart; ignore them. */
function isTypeOnly(info, name) {
  return info.typeOnly?.has(name);
}

// The root types file is generated: an explicit export list per module.
// A name that several modules provide comes from the winner that src/index.js
// re-exports explicitly; without a winner the runtime drops it, so do we.
const rootFile = join(LIB, 'types', 'index.d.ts');
const generated = renderRoot();
if (process.argv.includes('--write-root')) {
  writeFileSync(rootFile, generated);
  console.log(`types-check: wrote ${relative(LIB, rootFile)}`);
} else if (readFileSync(rootFile, 'utf8') !== generated) {
  errors.push('types/index.d.ts is out of date: run node tasks/types-check.js --write-root');
}

function renderRoot() {
  const src = readFileSync(join(LIB, 'src', 'index.js'), 'utf8');
  const modules = [...src.matchAll(/^export \* from '\.\/(core\/[\w-]+)\/index\.js';$/gm)].map((m) => m[1]);
  const typed = modules.map((dir) => {
    const file = join(LIB, 'types', dir, 'index.d.ts');
    const reader = exportReader([file]);
    return { dir, info: reader(file) };
  });
  const seen = new Map();
  for (const { info } of typed) for (const n of info.names) seen.set(n, (seen.get(n) ?? 0) + 1);

  // Explicit winners: `export { a, b } from './core/x/index.js';`
  const winner = new Map();
  for (const m of src.matchAll(/^export \{([^}]*)\} from '\.\/(core\/[\w-]+)\/index\.js';$/gm)) {
    for (const n of m[1].split(',').map((x) => x.trim()).filter(Boolean)) winner.set(n, m[2]);
  }
  const dropped = [...seen].filter(([n, c]) => c > 1 && !winner.has(n)).map(([n]) => n).sort();
  const included = (dir, n) => (winner.has(n) ? winner.get(n) === dir : seen.get(n) === 1);

  const out = [
    '/**',
    ' * types/index.d.ts',
    ' *',
    ' * GENERATED by `node tasks/types-check.js --write-root`. Do not edit.',
    ' *',
    ' * Types for the root entry `@anzaui/anza`: the flat re-export of',
    ' * src/index.js. Names exported by several modules come from the winner',
    ' * src/index.js re-exports explicitly: ' + [...winner].map(([n, d]) => `${n} (${d})`).sort().join(', '),
    ...(dropped.length ? [' * Dropped (no winner; import from the subpath): ' + dropped.join(', ')] : []),
    ' */',
    ''
  ];
  for (const { dir, info } of typed) {
    const names = [...info.names].filter((n) => included(dir, n)).sort();
    const items = names.map((n) => (info.typeOnly.has(n) ? `type ${n}` : n));
    out.push('export {');
    out.push(items.map((i) => '  ' + i).join(',\n'));
    out.push(`} from './${dir}/index.js';`);
    out.push('');
  }
  return out.join('\n');
}

for (const w of warnings) console.warn('warning: ' + w);
if (errors.length || (strict && warnings.length)) {
  console.error(`\ntypes-check: ${errors.length} error(s)${strict ? `, ${warnings.length} warning(s)` : ''}\n`);
  for (const e of errors) console.error('  ' + e);
  process.exit(1);
}
console.log(`types-check: ok (${checked} subpaths, ${warnings.length} warning(s))`);
