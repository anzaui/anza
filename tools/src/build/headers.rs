// tools/src/build/headers.rs
//
// Generates `dist/_headers` (Cloudflare Workers static assets / Pages format,
// also read by Netlify): cache rules for every response plus `Link` preload
// headers per SSG route, which Cloudflare turns into 103 Early Hints.
//
// Format limits (Cloudflare): at most 100 rules, at most 2,000 characters per
// line, and the values of a header set by several matching rules are joined
// with a comma. So there is exactly one Cache-Control rule, each route's Link
// header is one line (the most important preloads first), and when there are
// too many routes for one rule each, routes are grouped by first path segment.

use std::collections::BTreeMap;
use std::path::Path;

/// Output file name inside dist.
pub const FILE: &str = "_headers";

/// Cloudflare's per-file rule limit.
const MAX_RULES: usize = 100;
/// Cloudflare's per-line limit (indent, name and value included).
const MAX_LINE: usize = 2000;

/// Cache policy for every file whose name is not content-hashed: the browser
/// revalidates (cheap 304 with ETag) instead of trusting a stale copy. HTML,
/// sw.js, importmap.json and routes.json always stay `no-cache`.
const CACHE_ALL: &str = "no-cache";

/// Content-hashed files (production `dist/assets/`) never change under the
/// same URL, so browsers may keep them for a year without revalidating.
pub const ASSETS_PATTERN: &str = "/assets/*";
pub const CACHE_IMMUTABLE: &str = "public, max-age=31536000, immutable";

/// What one SSG route should preload (site-root URLs, no deploy base).
#[derive(Debug, Clone, Default, PartialEq, Eq)]
pub struct Hints {
  /// Route path (`/`, `/docs/x`).
  pub path: String,
  /// Stylesheets, render-blocking ones first.
  pub styles: Vec<String>,
  /// Modules, most important first.
  pub modules: Vec<String>,
}

/// Write `dist/_headers`. URLs and patterns get the deploy `base`.
pub fn emit(dist_dir: &Path, base: &str, routes: &[Hints]) -> Result<(), String> {
  let text = render(base, routes);
  crate::fs_atomic::write(&dist_dir.join(FILE), text.as_bytes())
}

/// The `_headers` file content (deterministic: routes are sorted).
pub fn render(base: &str, routes: &[Hints]) -> String {
  let with_base = |p: &str| super::base::with_base(base, p);
  let mut out = String::new();
  out.push_str("# Generated by `anza build`. Do not edit.\n");
  out.push_str("# Cache rules for every file, and per-route Link preloads (103 Early Hints).\n");
  out.push_str(&format!("{}\n  Cache-Control: {}\n", with_base("/*"), CACHE_ALL));
  // `! Cache-Control` detaches the `/*` value; otherwise Cloudflare joins
  // both rules' values into one header.
  out.push_str(&format!(
    "{}\n  ! Cache-Control\n  Cache-Control: {}\n",
    with_base(ASSETS_PATTERN),
    CACHE_IMMUTABLE
  ));

  let mut sorted: Vec<&Hints> = routes.iter().collect();
  sorted.sort_by(|a, b| a.path.cmp(&b.path));

  let mut budget = MAX_RULES - 2;
  for (patterns, hints) in link_rules(&sorted) {
    if patterns.len() > budget {
      break;
    }
    let Some(link) = link_line(&hints, &with_base) else {
      continue;
    };
    budget -= patterns.len();
    for pattern in patterns {
      out.push_str(&with_base(&pattern));
      out.push('\n');
      out.push_str(&link);
    }
  }
  out
}

/// Rules as (URL patterns, preloads). One rule per route when they all fit;
/// otherwise one per first path segment with the preloads that every route
/// of the group shares (in the first route's order).
fn link_rules(routes: &[&Hints]) -> Vec<(Vec<String>, Hints)> {
  let per_route: usize = routes.iter().map(|h| route_patterns(&h.path).len()).sum();
  if per_route <= MAX_RULES - 2 {
    return routes
      .iter()
      .map(|h| (route_patterns(&h.path), (*h).clone()))
      .collect();
  }
  let mut groups: BTreeMap<String, Vec<&Hints>> = BTreeMap::new();
  for hints in routes {
    let segment = hints.path.trim_start_matches('/').split('/').next().unwrap_or("");
    groups.entry(segment.to_string()).or_default().push(hints);
  }
  let shared = |list: &[&Hints], pick: fn(&Hints) -> &Vec<String>| -> Vec<String> {
    pick(list[0])
      .iter()
      .filter(|url| list[1..].iter().all(|h| pick(h).contains(url)))
      .cloned()
      .collect()
  };
  groups
    .into_iter()
    .map(|(segment, list)| {
      let patterns = if segment.is_empty() {
        vec!["/".to_string()]
      } else {
        vec![format!("/{}", segment), format!("/{}/*", segment)]
      };
      let hints = Hints {
        path: format!("/{}", segment),
        styles: shared(&list, |h| &h.styles),
        modules: shared(&list, |h| &h.modules),
      };
      (patterns, hints)
    })
    .collect()
}

/// A route is requested with or without a trailing slash depending on the
/// host's HTML handling, so both forms get the header.
fn route_patterns(path: &str) -> Vec<String> {
  let trimmed = path.trim_end_matches('/');
  if trimmed.is_empty() {
    vec!["/".to_string()]
  } else {
    vec![trimmed.to_string(), format!("{}/", trimmed)]
  }
}

/// One `  Link: …` line (with newline): stylesheets, then modules, cut at the
/// first entry that would exceed the line limit. None when nothing fits.
fn link_line(hints: &Hints, with_base: &dyn Fn(&str) -> String) -> Option<String> {
  let entries = hints
    .styles
    .iter()
    .map(|s| format!("<{}>; rel=preload; as=style", with_base(s)))
    .chain(hints.modules.iter().map(|m| format!("<{}>; rel=modulepreload", with_base(m))));
  let mut line = String::from("  Link: ");
  let mut count = 0usize;
  for entry in entries {
    let extra = if count == 0 { entry.len() } else { entry.len() + 2 };
    if line.len() + extra > MAX_LINE {
      break;
    }
    if count > 0 {
      line.push_str(", ");
    }
    line.push_str(&entry);
    count += 1;
  }
  (count > 0).then(|| {
    line.push('\n');
    line
  })
}

#[cfg(test)]
mod tests {
  use super::*;

  fn hints(path: &str, modules: Vec<String>) -> Hints {
    Hints {
      path: path.to_string(),
      styles: vec!["/tokens/index.css".into()],
      modules,
    }
  }

  #[test]
  fn per_route_rules_with_both_slash_forms() {
    let routes = vec![
      hints("/docs/b", vec!["/app.js".to_string(), "/b.js".to_string()]),
      hints("/", vec!["/app.js".to_string()]),
    ];
    let text = render("", &routes);
    assert!(text.starts_with("# Generated"));
    assert!(text.contains("/*\n  Cache-Control: no-cache\n"));
    assert!(text.contains(
      "/assets/*\n  ! Cache-Control\n  Cache-Control: public, max-age=31536000, immutable\n"
    ));
    assert!(text.contains(
      "\n/\n  Link: </tokens/index.css>; rel=preload; as=style, </app.js>; rel=modulepreload\n"
    ));
    assert!(text.contains("\n/docs/b\n  Link: "));
    assert!(text.contains("\n/docs/b/\n  Link: "));
    assert!(text.contains("</b.js>; rel=modulepreload\n"));
    // Sorted: `/` before `/docs/b`.
    assert!(text.find("\n/\n").unwrap() < text.find("\n/docs/b\n").unwrap());
  }

  #[test]
  fn many_routes_group_by_segment_and_stay_in_limits() {
    let mut routes = Vec::new();
    for i in 0..200 {
      let mut modules = vec!["/app.js".to_string(), "/core.js".to_string()];
      modules.push(format!("/docs/p{i}.js"));
      for j in 0..100 {
        modules.push(format!("/lib/module-with-a-long-name-{j}.js"));
      }
      routes.push(hints(&format!("/docs/p{i}"), modules));
    }
    routes.push(hints("/", vec!["/app.js".to_string()]));
    let text = render("/base", &routes);
    let rules = text.lines().filter(|l| !l.starts_with(' ') && !l.starts_with('#')).count();
    assert!(rules <= MAX_RULES, "{rules} rules");
    assert!(text.lines().all(|l| l.len() <= MAX_LINE));
    assert!(text.contains("\n/base/docs\n  Link: "));
    assert!(text.contains("\n/base/docs/*\n  Link: "));
    assert!(text.starts_with("# Generated"));
    assert!(text.contains("/base/*\n  Cache-Control: no-cache\n"));
    // Only modules shared by every route of the group.
    assert!(!text.contains("/docs/p1.js"));
    assert!(text.contains("</base/core.js>; rel=modulepreload"));
  }
}
