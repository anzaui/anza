fn render_sidebar(sections: &[SidebarSection], active: &str, _base: &str) -> String {
  let mut out = String::new();
  for (i, section) in sections.iter().enumerate() {
    if i > 0 {
      out.push_str("        <div class=\"sidebar-divider\"></div>\n");
    }
    out.push_str("        <details class=\"sidebar-group\" open>\n");
    out.push_str("          <summary class=\"sidebar-group-header\">\n");
    out.push_str(&format!("            <h3>{}</h3>\n", esc(&section.title)));
    out.push_str("          </summary>\n");
    out.push_str("          <div class=\"sidebar-group-links\">\n");
    for item in &section.items {
      if item.hide {
        continue;
      }
      let href = item_href(item, _base);
      let label = item
        .label
        .clone()
        .unwrap_or_else(|| fallback_label(&item.path));
      let class = if href == active || active.starts_with(&(href.clone() + "/")) {
        " class=\"active\""
      } else {
        ""
      };
      out.push_str(&format!(
        "            <a href=\"{href}\"{class}>{label}</a>\n",
        href = esc(&href),
        class = class,
        label = esc(&label),
      ));
    }
    out.push_str("          </div>\n");
    out.push_str("        </details>\n");
  }
  out
}

fn item_href(item: &SidebarItem, base: &str) -> String {
  let p = item.path.trim_end_matches(".md").replace('\\', "/");
  if p == "index" {
    return base.trim_end_matches('/').to_string();
  }
  format!("{}/{}", base.trim_end_matches('/'), p)
}

fn fallback_label(path: &str) -> String {
  Path::new(path)
    .file_stem()
    .and_then(|s| s.to_str())
    .unwrap_or(path)
    .to_string()
}

fn emit_redirects(out: &Path, cfg: &DocsConfig) -> Result<(), String> {
  for redir in &cfg.redirect {
    let trimmed = redir.from.trim_start_matches('/');
    let dir = out.join(trimmed);
    fs::create_dir_all(&dir).map_err(|e| e.to_string())?;
    let html = format!(
      r#"<!DOCTYPE html>
<html lang="en"><head>
<meta charset="utf-8" />
<meta http-equiv="refresh" content="0;url={to}" />
<script>location.replace({to_js});</script>
<title>Redirect</title>
</head><body><p>Redirecting to <a href="{to}">{to}</a>…</p></body></html>
"#,
      to = esc(&redir.to),
      to_js = serde_json::to_string(&redir.to).unwrap_or_else(|_| "\"/\"".into()),
    );
    fs::write(dir.join("index.html"), html).map_err(|e| e.to_string())?;
  }
  Ok(())
}

fn emit_root_index(out: &Path, cfg: &DocsConfig) -> Result<(), String> {
  let to = &cfg.entry.route;
  let html = format!(
    r#"<!DOCTYPE html>
<html lang="en"><head>
<meta charset="utf-8" />
<meta http-equiv="refresh" content="0;url={to}" />
<script>location.replace({to_js});</script>
<title>{site}</title>
</head><body><p><a href="{to}">Open docs</a></p>
<script type="module" src="/app.js"></script>
</body></html>
"#,
    to = esc(to),
    to_js = serde_json::to_string(to).unwrap(),
    site = esc(&cfg.site.title),
  );
  fs::write(out.join("index.html"), html).map_err(|e| e.to_string())
}

