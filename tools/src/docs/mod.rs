fn emit_page(out: &Path, cfg: &DocsConfig, page: &Page) -> Result<(), String> {
  let dir = route_to_dir(out, &page.route, &cfg.entry.route)?;
  fs::create_dir_all(&dir).map_err(|e| e.to_string())?;

  let html = render_shell(cfg, page);
  fs::write(dir.join("index.html"), html).map_err(|e| e.to_string())?;

  // Soft-nav page module stub (future Anza page() registration).
  let tag = tag_from_route(&page.route, &cfg.site.base);
  let via = cfg
    .entry
    .via
    .iter()
    .map(|s| format!("'{s}'"))
    .collect::<Vec<_>>()
    .join(", ");
  let js = format!(
    r#"// Generated stub — full Anza page() wiring lands when docs emit uses library runtime.
// route: {route}
export const route = '{route}';
export const tag = '{tag}';
export const via = [{via}];
export const template = {{ html: './index.html' }};
export const style = ['/styles/shared.css'];
console.debug('[anza docs]', route, tag);
"#,
    route = page.route,
    tag = tag,
    via = via,
  );
  // Home HTML lives at docs/index.html; module stub at docs/home.js to avoid barrel self-import.
  let js_path = if page.route == cfg.entry.route {
    out.join("docs").join("home.js")
  } else {
    dir.join("index.js")
  };
  fs::write(js_path, js).map_err(|e| e.to_string())?;
  Ok(())
}

fn route_to_dir(out: &Path, route: &str, home_route: &str) -> Result<PathBuf, String> {
  if route == home_route {
    return Ok(out.join("docs"));
  }
  let trimmed = route.trim_start_matches('/');
  Ok(out.join(trimmed))
}

fn route_to_dist_js(route: &str, home_route: &str) -> String {
  // Paths relative to dist/docs/index.js barrel.
  if route == home_route {
    return "./home.js".into();
  }
  if let Some(rest) = route.strip_prefix("/docs/") {
    return format!("./{rest}/index.js");
  }
  format!("./{}/index.js", route.trim_start_matches('/'))
}

